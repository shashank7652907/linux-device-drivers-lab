{
    kthread_stop(rx_thread);
    filp_close(uart_fp, NULL);
    filp_close(log_fp, NULL);
    i2c_unregister_device(oled_client);
    i2c_del_driver(&oled_driver);
    pr_info(DRIVER ": unloaded\n");
}

