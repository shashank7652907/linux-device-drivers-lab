/*
 * ultrasonic_rx.c
 *
 * Combined UART receiver + SSD1306 OLED display driver.
 *
 * - kthread reads "DIST:NNN TIME:NNN\n" frames from /dev/serial0
 * - Parses the distance value
 * - Displays "DIST: NNN" on the 128x32 SSD1306 OLED via I2C
 * - Appends each frame to /var/log/ultrasonic_rx.log
 *
 * Before insmod:
 *   stty -F /dev/serial0 115200 raw cs8 -cstopb -parenb clocal cread -echo min 1 time 0
 *
 * Wiring (RX Pi):
 *   UART RX  ← GPIO15 (serial0) ← TX Pi UART TX
 *   I2C SDA  ← GPIO2  (i2c-1)
 *   I2C SCL  ← GPIO3  (i2c-1)
 *   OLED addr 0x3C
 */

